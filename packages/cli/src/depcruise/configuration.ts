import type { Config } from '../config.js';

/**
 * The dependency-cruiser rules of a project, derived from its config: the layer and context
 * boundaries on the resolved import graph, then cycles, orphans and package hygiene. Ported
 * from pipeline/depcruise-config.mjs; a test holds the two to the same output.
 */
interface CruiseRule {
  readonly name: string;
  readonly severity: 'error';
  readonly comment: string;
  readonly from: Readonly<Record<string, unknown>>;
  readonly to: Readonly<Record<string, unknown>>;
}

export interface CruiseConfiguration {
  readonly forbidden: readonly CruiseRule[];
  readonly options: Readonly<Record<string, unknown>>;
}

export const DEPCRUISE_FILE = '.dependency-cruiser.cjs';
const PROJECT_CONFIG = 'ddd-ts-kit.config.json';

export function cruiseConfiguration(config: Config): CruiseConfiguration {
  return { forbidden: [...layerRules(config), ...contextRules(config), ...hygieneRules(config)], options: cruiseOptions() };
}

/** The file dependency-cruiser loads: plain data, regenerated whenever the config changes. */
export function renderCruiseFile(config: Config): string {
  const header = `// Generated by \`ddd-ts-kit depcruise-config\` from ${PROJECT_CONFIG}. Do not edit: change the config, then regenerate.`;
  return `${header}\n/* global module -- a CommonJS file, as dependency-cruiser loads it */\nmodule.exports = ${JSON.stringify(cruiseConfiguration(config), null, 2)};\n`;
}

function layerRules(config: Config): CruiseRule[] {
  const context = `^${escape(config.contextsDir)}/([^/]+)`;
  const own = (layer: string): string => `^${escape(config.contextsDir)}/$1/${layer}(/|\\.ts$)`;
  const sharedKernel = `^${escape(config.sharedKernelDir)}/`;
  const otherContexts = `^${escape(config.contextsDir)}/(?!$1/)[^/]+/`;
  return [
    {
      name: 'layer-domain-purity',
      severity: 'error',
      comment: 'domain/ imports only its own domain/, the shared kernel and the allowed kernel packages. Invert the dependency: declare the need as an interface in domain/ or a port in application/ports.',
      from: { path: `${context}/domain/`, pathNot: testFiles(config) },
      to: { pathNot: [own('domain'), sharedKernel, internalsOfOthers(config), ...packages(config.domainAllowedPackages)] },
    },
    {
      name: 'layer-application-inward',
      severity: 'error',
      comment: 'application/ imports domain/, application/, published languages and the allowed kernel packages. Depend on a port and let the module file bind the adapter.',
      from: { path: `${context}/application/`, pathNot: testFiles(config) },
      to: { pathNot: [own('domain'), own('application'), own('published-language'), sharedKernel, otherContexts, ...packages(config.applicationAllowedPackages)] },
    },
    sideways(config, { from: 'presentation', to: 'infrastructure', instead: 'Go through the command or query bus; the adapter is bound in the module file.' }),
    sideways(config, { from: 'infrastructure', to: 'presentation', instead: 'Move the shared type to application/ and let both sides import it from there.' }),
  ];
}

interface Sideways {
  readonly from: string;
  readonly to: string;
  readonly instead: string;
}

function sideways(config: Config, { from, to, instead }: Sideways): CruiseRule {
  const contexts = `^${escape(config.contextsDir)}`;
  return {
    name: `layer-${from}-no-${to}`,
    severity: 'error',
    comment: `${from}/ never imports ${to}/. ${instead}`,
    from: { path: `${contexts}/([^/]+)/${from}/`, pathNot: testFiles(config) },
    to: { path: `${contexts}/$1/${to}(/|\\.ts$)` },
  };
}

/** Another context reached outside its published language: context-published-language-only reports it, once. */
function internalsOfOthers(config: Config): string {
  return `^${escape(config.contextsDir)}/(?!$1/)[^/]+/(?!published-language(/|\\.ts$))`;
}

function contextRules(config: Config): CruiseRule[] {
  const contexts = `^${escape(config.contextsDir)}`;
  const publishedLanguage = `${contexts}/[^/]+/published-language(/|\\.ts$)`;
  const declared = Object.keys(config.contexts);
  return [
    {
      name: 'context-published-language-only',
      severity: 'error',
      comment: "A file imports from another context only through that context's published-language/. Publish the missing contract there or react to an integration event.",
      from: { path: `${contexts}/([^/]+)/` },
      to: { path: `${contexts}/[^/]+/`, pathNot: [`${contexts}/$1/`, publishedLanguage] },
    },
    ...declared.map((name) => declaredRelationship(config, name)),
    {
      name: 'context-declared-relationship',
      severity: 'error',
      comment: `A context missing from ${PROJECT_CONFIG} declares no upstream. Add it to "contexts" with its upstreams.`,
      from: { path: `${contexts}/([^/]+)/`, pathNot: declared.map((name) => `${contexts}/${escape(name)}/`) },
      to: { path: publishedLanguage, pathNot: `${contexts}/$1/` },
    },
    {
      name: 'context-published-language-is-a-contract',
      severity: 'error',
      comment: 'published-language/ imports only its allowed packages and other published languages. Declare the contract with plain serializable types written in that folder.',
      from: { path: publishedLanguage, pathNot: testFiles(config) },
      to: { pathNot: [publishedLanguage, ...packages(config.publishedLanguageAllowedPackages)] },
    },
  ];
}

function declaredRelationship(config: Config, name: string): CruiseRule {
  const contexts = `^${escape(config.contextsDir)}`;
  const upstreams = config.contexts[name]?.upstreams.map((upstream) => upstream.context) ?? [];
  const allowed = [name, ...upstreams].map(escape).join('|');
  return {
    name: 'context-declared-relationship',
    severity: 'error',
    comment: `"${name}" imports the published language of a context that is not one of its upstreams. Declare the relationship under contexts.${name}.upstreams in ${PROJECT_CONFIG}, after checking that the direction is intended.`,
    from: { path: `${contexts}/${escape(name)}/` },
    to: { path: `${contexts}/[^/]+/published-language(/|\\.ts$)`, pathNot: `${contexts}/(${allowed})/` },
  };
}

function hygieneRules(config: Config): CruiseRule[] {
  return [
    {
      name: 'no-circular',
      severity: 'error',
      comment: 'Two modules that need each other are one module, or hide a third concept. Extract what both use, or invert one direction with an interface.',
      from: {},
      to: { circular: true },
    },
    {
      name: 'no-orphans',
      severity: 'error',
      comment: 'Nothing imports this file. Delete it, or register it in the module file of its context.',
      from: { orphan: true, pathNot: orphanExceptions(config) },
      to: {},
    },
    {
      name: 'not-to-undeclared-dependency',
      severity: 'error',
      comment: 'The package is not in package.json, or cannot be resolved. Declare it, or fix the specifier.',
      from: {},
      to: { dependencyTypes: ['npm-no-pkg', 'npm-unknown', 'unknown'] },
    },
    ...productionRules(config),
  ];
}

function productionRules(config: Config): CruiseRule[] {
  const production = { path: `^${escape(config.sourceRoot)}/`, pathNot: testFiles(config) };
  return [
    {
      name: 'not-to-dev-dependency',
      severity: 'error',
      comment: 'Production code imports a package listed under devDependencies: it is absent from the production image. Move it to dependencies, or keep the import in a test.',
      from: production,
      to: { dependencyTypes: ['npm-dev'], dependencyTypesNot: ['type-only'], pathNot: ['node_modules/@types/'] },
    },
    {
      name: 'not-to-test',
      severity: 'error',
      comment: 'Production code imports a test file (spec, fake, builder, test support). Move what is shared to the layer that owns it.',
      from: production,
      to: { path: testFiles(config) },
    },
  ];
}

function testFiles(config: Config): string[] {
  return [`^${escape(config.contextsDir)}/[^/]+/test/`, '\\.(spec|test)\\.[cm]?ts$', '(^|/)testing\\.ts$', '^test/'];
}

/** Entry points, files loaded by a tool instead of an import, and the fakes a context keeps ready for the tests to come. */
function orphanExceptions(config: Config): string[] {
  return [
    `^${escape(config.sourceRoot)}/main\\.ts$`,
    `^${escape(config.platformDir)}/tracing\\.ts$`,
    `^${escape(config.contextsDir)}/[^/]+/published-language/`,
    `^${escape(config.contextsDir)}/[^/]+/test/fakes/`,
    '\\.d\\.[cm]?ts$',
    '\\.(spec|test)\\.[cm]?ts$',
    '(^|/)[^/]+\\.config\\.[cm]?[jt]s$',
    '^scripts/',
  ];
}

/** A package as resolved in node_modules, as a linked workspace, or as written when it is not installed. */
function packages(names: readonly string[]): string[] {
  return names.flatMap((name) => [`(^|/)node_modules/${escape(name)}/`, `^${escape(name)}(/|$)`]);
}

function escape(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * The parser is the compiler API of `typescript` 6, which the generated project installs for
 * its tools next to the native compiler: it tells type-only imports apart.
 */
function cruiseOptions(): Record<string, unknown> {
  return {
    parser: 'tsc',
    doNotFollow: { path: ['node_modules'] },
    exclude: { path: ['^dist/', '^coverage/'] },
    tsPreCompilationDeps: true,
    tsConfig: { fileName: 'tsconfig.json' },
    enhancedResolveOptions: {
      exportsFields: ['exports'],
      conditionNames: ['import', 'node', 'default', 'types'],
      mainFields: ['module', 'main', 'types', 'typings'],
    },
    skipAnalysisNotInRules: true,
    reporterOptions: { text: { highlightFocused: true } },
  };
}

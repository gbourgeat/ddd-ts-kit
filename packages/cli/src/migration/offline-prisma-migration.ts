import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import type { Io } from '../commands/io';
import { errorCodeOf } from '../workspace/error-code-of';
import { runOnInProcessDatabase } from './run-on-in-process-database';

export interface OfflinePrismaMigration {
  readonly root: string;
  /** Where the migrations are, relative to the root. */
  readonly folder: string;
  /** What the migration does, as the user typed it. */
  readonly name: string;
  readonly io: Io;
  readonly now?: Date;
}

const LOCK = `# Please do not edit this file manually
# It should be added in your version-control system (e.g., Git)
provider = "postgresql"
`;

/** The exit code of `prisma migrate diff --exit-code` when the two sides differ. */
const DIFFERENT = 2;

/**
 * `prisma migrate dev --create-only` without a server: Prisma diffs the migrations of the project,
 * replayed on a PostgreSQL started in process (its shadow database), against the schema, and the
 * migration is written the way `migrate dev` writes it. Answers the exit code; 0 and no file when
 * the schema is already what the migrations build.
 */
export function offlinePrismaMigration(migration: OfflinePrismaMigration): number {
  const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'prisma-diff-'));
  const script = path.join(scratch, 'migration.sql');

  try {
    const code = diffOnInProcessDatabase(migration, script);

    if (code === 0) {
      migration.io.out('Already in sync, no schema change or pending migration was found.\n');
    }

    return code === DIFFERENT ? write(migration, script) : code;
  } finally {
    fs.rmSync(scratch, { recursive: true, force: true });
  }
}

/** Replays the migrations on the in-process database and writes the SQL that leads to the schema into `script`. */
function diffOnInProcessDatabase({ root, folder }: OfflinePrismaMigration, script: string): number {
  const migrations = path.join(root, folder);
  const lock = path.join(migrations, 'migration_lock.toml');

  fs.mkdirSync(migrations, { recursive: true });
  writeLockUnlessPresent(lock);

  return runOnInProcessDatabase(root, [
    {
      bin: 'prisma/build/index.js',
      args: [
        'migrate',
        'diff',
        '--from-migrations',
        folder,
        '--to-schema',
        'prisma/schema',
        '--script',
        '--exit-code',
        '-o',
        script,
      ],
      env: { SHADOW_DATABASE_URL: '{url}' },
    },
  ]);
}

function write({ root, folder, name, io, now = new Date() }: OfflinePrismaMigration, script: string): number {
  const directory = path.join(root, folder, `${timestampOf(now)}_${slugOf(name)}`);

  fs.mkdirSync(directory);
  fs.copyFileSync(script, path.join(directory, 'migration.sql'));
  io.out(`Prisma Migrate created the following migration without applying it ${path.basename(directory)}\n`);

  return 0;
}

/** `20261028185157`, in UTC, as Prisma prefixes its migrations. */
function timestampOf(date: Date): string {
  return date
    .toISOString()
    .replace(/\.\d{3}Z$/, '')
    .replace(/[-:T]/g, '');
}

/** What Prisma makes of a name: lower case, accents dropped, anything but letters and digits an underscore. */
function slugOf(name: string): string {
  return name
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');
}

/** Writes the lock of a first migration in one step, so that a lock already there is never overwritten. */
function writeLockUnlessPresent(lock: string): void {
  try {
    fs.writeFileSync(lock, LOCK, { flag: 'wx' });
  } catch (error) {
    if (errorCodeOf(error) !== 'EEXIST') {
      throw error;
    }
  }
}

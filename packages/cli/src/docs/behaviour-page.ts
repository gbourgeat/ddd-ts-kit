import { allRules } from './all-rules';
import { citedRows } from './cited-rows';
import { countsOf, type PageCounts } from './counts-of';
import type { PageEntry, PageSection } from './page-section';
import type { RuleGroup, SpecRules, StatedRule } from './rules-in';
import { readableTitle } from './readable-title';
import { rulesWhere } from './rules-where';

/** The sub-list of a heading that holds the titles a template of the kit wrote, after the rules written for the project. */
const GENERATED = '*Generated by the kit*';

/**
 * A page of what the tests state, in the words of their titles: a heading, how it is made, the
 * counts, then one section per part of the page (the use cases, the model, the reactions, a
 * directory of specs), one heading per entry, the specs it reads and their rules as they are
 * grouped, the titles a template of the kit wrote listed apart after them, so that the eye goes to
 * what was written for the project. A planned rule (`it.todo`) comes last and says so, and so does
 * one put aside (`.skip`). A title that cites the rows of the plan it serves shows them before the
 * rule, and the page ends with the rows its titles cite.
 */
export function behaviourPage(heading: string, intro: string, sections: readonly PageSection[]): string {
  const body = sections.filter((section) => section.entries.length > 0).flatMap(sectionLines);

  return [
    `# ${heading}`,
    '',
    intro,
    '',
    summary(countsOf(sections)),
    ...(body.length === 0 ? ['', 'No spec yet.'] : [...body, ...rowsLines(sections)]),
    '',
  ].join('\n');
}

function summary({ stated, planned, aside, generated, specs }: PageCounts): string {
  const parts = [
    `${stated} ${stated === 1 ? 'rule' : 'rules'} stated`,
    ...(planned > 0 ? [`${planned} planned`] : []),
    ...(aside > 0 ? [`${aside} put aside`] : []),
  ];

  const apart =
    generated === 0
      ? ''
      : ` Of the ${stated + planned + aside} titles, ${generated} are as the kit generated them, listed apart under each heading.`;

  return `${parts.join(', ')}, in ${specs} ${specs === 1 ? 'spec' : 'specs'}.${apart}`;
}

function sectionLines(section: PageSection): string[] {
  return ['', `## ${section.title}`, ...section.entries.flatMap(entryLines)];
}

/** The rules written for the project, spec after spec, then those a template wrote, under the `describe` of their spec still. */
function entryLines({ heading, specs }: PageEntry): string[] {
  const generated = specs.flatMap((spec) =>
    rulesLines(
      rulesWhere(spec.rules, (rule) => spec.generated.has(rule)),
      1,
    ),
  );

  return [
    '',
    `### ${heading}`,
    '',
    specs.map((spec) => `\`${spec.file}\`${spec.note === undefined ? '' : ` (${spec.note})`}`).join(', '),
    '',
    ...specs.flatMap((spec) =>
      rulesLines(
        rulesWhere(spec.rules, (rule) => !spec.generated.has(rule)),
        0,
      ),
    ),
    ...(generated.length === 0 ? [] : [`- ${GENERATED}`, ...generated]),
  ];
}

function rulesLines(rules: SpecRules, depth: number): string[] {
  return [
    ...plannedLast(rules.rules).map((rule) => ruleLine(rule, depth)),
    ...rules.groups.flatMap((group) => groupLines(group, depth)),
  ];
}

/** `#US5.02 AC1 places an order` reads ``- `#US5.02 AC1` places an order``: the rows and the criterion it serves, then the rule. */
function ruleLine(rule: StatedRule, depth: number): string {
  const { prefix, text } = citedRows(rule.title);

  return `${'  '.repeat(depth)}- ${prefix === '' || text === rule.title ? '' : `\`${prefix}\` `}${readableTitle(text)}${suffix(rule.state)}`;
}

/** The rows of the plan the titles of the page cite, and how many titles cite each, so that a reviewer checks that each rule line of a row has its title. */
function rowsLines(sections: readonly PageSection[]): string[] {
  const cited = new Map<string, number>();

  const specs = sections.flatMap((section) => section.entries.flatMap((entry) => entry.specs));

  for (const rule of specs.flatMap((spec) => allRules(spec.rules))) {
    for (const row of new Set(citedRows(rule.title).rows)) {
      cited.set(row, (cited.get(row) ?? 0) + 1);
    }
  }

  return [
    '',
    '## Rows of the plan',
    '',
    cited.size === 0
      ? 'No title cites a row of `docs/architecture/slices.md` yet: a title opens with the row it serves and the criterion it proves, `#US5.02 AC1 ...`.'
      : 'The rows of `docs/architecture/slices.md` the titles of this page cite, and how many titles cite each: each rule line of a row has its title.',
    ...(cited.size === 0 ? [] : ['', '| Row | Titles |', '|---|---|']),
    ...[...cited]
      .sort(([left], [right]) => left.localeCompare(right, 'en', { numeric: true }))
      .map(([row, titles]) => `| \`#${row}\` | ${titles} |`),
  ];
}

/** The rules written first, those still to write (`it.todo`) after them, each in the order of the file. */
function plannedLast(rules: readonly StatedRule[]): StatedRule[] {
  return [...rules.filter((rule) => rule.state !== 'planned'), ...rules.filter((rule) => rule.state === 'planned')];
}

function groupLines(group: RuleGroup, depth: number): string[] {
  return [`${'  '.repeat(depth)}- **${readableTitle(group.title)}**`, ...rulesLines(group, depth + 1)];
}

function suffix(state: 'stated' | 'planned' | 'aside'): string {
  return state === 'planned' ? ' (planned)' : state === 'aside' ? ' (put aside)' : '';
}

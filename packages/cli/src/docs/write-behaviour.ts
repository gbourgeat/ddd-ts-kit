import type { Config } from '../config';
import { describeContext } from '../describe/describe-context';
import type { Workspace } from '../workspace';
import { behaviourPage } from './behaviour-page';
import type { ContextFacts } from './context-facts';
import { contextSections } from './context-sections';
import { countsOf, type PageCounts } from './counts-of';
import { joinedSpecs, type UseCasesAndSpecs } from './joined-specs';
import type { SpecOfPage } from './page-section';
import { rulesIn } from './rules-in';
import { specOfPage } from './spec-of-page';
import { specsByDirectory } from './specs-by-directory';

/** Where the pages of what the tests state live: one per context, one for the application, and their index. */
const BEHAVIOUR_DIR = 'docs/behaviour';
const APPLICATION = 'application';

interface WrittenPage {
  readonly name: string;
  readonly title: string;
  readonly counts: PageCounts;
}

/**
 * Writes the pages of what the tests state: one per context on disk, from the specs of its `test/`
 * directory and the end-to-end and acceptance specs of its use cases; one for the application,
 * from the other specs of the `test/` directory of the project (journeys, architecture); and the
 * index. A page of a context that is gone is deleted.
 */
export function writeBehaviour(ws: Workspace, config: Config, contexts: readonly ContextFacts[]): void {
  const onDisk: UseCasesAndSpecs[] = contexts
    .filter((candidate) => candidate.onDisk)
    .map((context) => ({
      context: context.name,
      known: describeContext(ws, config, context),
      specs: specsOf(ws, `${config.contextsDir}/${context.name}/test`),
    }));

  const joined = joinedSpecs(onDisk, specsOf(ws, 'test'));
  const pages: WrittenPage[] = [];

  for (const { context, known, specs } of onDisk) {
    const sections = contextSections({ context, known, specs, joined: joined.byContext.get(context) ?? new Map() });

    write(
      ws,
      `${BEHAVIOUR_DIR}/${context}.md`,
      behaviourPage(`${context}: what its tests state`, intro('of the context'), sections),
    );

    pages.push({ name: context, title: context, counts: countsOf(sections) });
  }

  pages.push(...writeApplicationPage(ws, joined.left));
  write(ws, `${BEHAVIOUR_DIR}/README.md`, indexPage(pages));
  deleteStalePages(ws, new Set([...pages.map((page) => `${page.name}.md`), 'README.md']));
}

/** The page of the specs of the application that serve no use case of a context, when there is one. */
function writeApplicationPage(ws: Workspace, specs: readonly SpecOfPage[]): WrittenPage[] {
  const sections = specsByDirectory(specs);

  if (sections.length === 0) {
    return [];
  }

  const page = behaviourPage(
    'The application: what its tests state',
    intro('of the application, outside the use cases of the contexts'),
    sections,
  );

  write(ws, `${BEHAVIOUR_DIR}/${APPLICATION}.md`, page);

  return [{ name: APPLICATION, title: 'the application', counts: countsOf(sections) }];
}

function intro(of: string): string {
  return `Generated by \`ddd-ts-kit docs\` from the titles of the specs${of === '' ? '' : ` ${of}`}. Do not edit by hand: a rule changes in its spec, then \`npm run docs:generate\`.`;
}

/** Every spec under the directory of tests, deepest included, sorted by path, named from that directory. */
function specsOf(ws: Workspace, testDir: string): SpecOfPage[] {
  return specsUnder(ws, testDir).map((file) =>
    specOfPage(file.slice(testDir.length + 1), rulesIn(ws.read(file) ?? '')),
  );
}

function specsUnder(ws: Workspace, directory: string): string[] {
  const here = ws
    .list(directory)
    .filter((file) => file.endsWith('.spec.ts'))
    .map((file) => `${directory}/${file}`);

  const below = ws.directories(directory).flatMap((child) => specsUnder(ws, `${directory}/${child}`));

  return [...here, ...below].sort();
}

function indexPage(pages: readonly WrittenPage[]): string {
  const rows = pages.map(
    ({ name, title, counts }) =>
      `| [${title}](${name}.md) | ${counts.stated} | ${counts.generated} | ${counts.planned} | ${counts.specs} |`,
  );

  return [
    '# What the tests state',
    '',
    intro(''),
    '',
    'Each page lists, in the words of the test titles, the rules a context holds, one heading per use case (its handler, policy, route, end-to-end and acceptance specs together), then per part of the model and per reaction: the rules written for the project first, the titles a template of the kit wrote apart after them (Generated), a planned rule (an `it.todo` still to write) last. A rule to change is changed in its spec; the test is the proof, the page its reading.',
    '',
    '| Page | Rules stated | Generated | Planned | Specs |',
    '|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

function deleteStalePages(ws: Workspace, kept: ReadonlySet<string>): void {
  for (const file of ws.list(BEHAVIOUR_DIR).filter((name) => name.endsWith('.md') && !kept.has(name))) {
    ws.delete(`${BEHAVIOUR_DIR}/${file}`);
  }
}

function write(ws: Workspace, file: string, content: string): void {
  if (ws.exists(file)) {
    ws.update(file, content);
  } else {
    ws.create(file, content);
  }
}

import type { Config } from '../config';
import type { Workspace } from '../workspace';
import { behaviourPage } from './behaviour-page';
import type { ContextFacts } from './context-facts';
import { countsOf, type PageCounts } from './counts-of';
import type { PageSection, SpecOfPage } from './page-section';
import { rulesIn } from './rules-in';

/** Where the pages of what the tests state live: one per context, one for the application, and their index. */
const BEHAVIOUR_DIR = 'docs/behaviour';
const APPLICATION = 'application';
/** The directories of tests of a context whose specs are read, in the order of the page; any other directory of specs follows. */
const FIRST = ['unit', 'integration'];
/** The heading of a directory of specs whose name is not a word. */
const SECTION_TITLES: Readonly<Record<string, string>> = { e2e: 'End-to-end specs' };

interface WrittenPage {
  readonly name: string;
  readonly title: string;
  readonly counts: PageCounts;
}

/**
 * Writes the pages of what the tests state: one per context on disk, from the specs of its `test/`
 * directory; one for the application, from the specs of the `test/` directory of the project (end
 * to end, acceptance, architecture); and the index. A page of a context that is gone is deleted.
 */
export function writeBehaviour(ws: Workspace, config: Config, contexts: readonly ContextFacts[]): void {
  const pages: WrittenPage[] = [];

  for (const context of contexts.filter((candidate) => candidate.onDisk)) {
    const sections = sectionsOf(ws, `${config.contextsDir}/${context.name}/test`);

    write(
      ws,
      `${BEHAVIOUR_DIR}/${context.name}.md`,
      behaviourPage(`${context.name}: what its tests state`, intro('of the context'), sections),
    );

    pages.push({ name: context.name, title: context.name, counts: countsOf(sections) });
  }

  const application = sectionsOf(ws, 'test');

  if (application.some((section) => section.specs.length > 0)) {
    const page = behaviourPage(
      'The application: what its tests state',
      intro('of the application, outside the contexts'),
      application,
    );

    write(ws, `${BEHAVIOUR_DIR}/${APPLICATION}.md`, page);
    pages.push({ name: APPLICATION, title: 'the application', counts: countsOf(application) });
  }

  write(ws, `${BEHAVIOUR_DIR}/README.md`, indexPage(pages));
  deleteStalePages(ws, new Set([...pages.map((page) => `${page.name}.md`), 'README.md']));
}

function intro(of: string): string {
  return `Generated by \`ddd-ts-kit docs\` from the titles of the specs${of === '' ? '' : ` ${of}`}. Do not edit by hand: a rule changes in its spec, then \`npm run docs:generate\`.`;
}

/** One section per directory of `testDir` that holds specs, `unit` and `integration` first, the specs at its root last. */
function sectionsOf(ws: Workspace, testDir: string): PageSection[] {
  const directories = ws.directories(testDir);

  const ordered = [
    ...FIRST.filter((name) => directories.includes(name)),
    ...directories.filter((name) => !FIRST.includes(name)),
  ];

  const sections = ordered.map((name) => ({
    title: SECTION_TITLES[name] ?? `${capitalised(name)} specs`,
    specs: specsUnder(ws, `${testDir}/${name}`).map((file) => specOf(ws, testDir, file)),
  }));

  const atRoot = ws.list(testDir).filter((file) => file.endsWith('.spec.ts'));

  return [
    ...sections,
    ...(atRoot.length === 0
      ? []
      : [{ title: 'Specs', specs: atRoot.map((file) => specOf(ws, testDir, `${testDir}/${file}`)) }]),
  ];
}

function specOf(ws: Workspace, testDir: string, file: string): SpecOfPage {
  return { file: file.slice(testDir.length + 1), rules: rulesIn(ws.read(file) ?? '') };
}

/** Every `*.spec.ts` under the directory, deepest included, sorted by path. */
function specsUnder(ws: Workspace, directory: string): string[] {
  const here = ws
    .list(directory)
    .filter((file) => file.endsWith('.spec.ts'))
    .map((file) => `${directory}/${file}`);

  const below = ws.directories(directory).flatMap((child) => specsUnder(ws, `${directory}/${child}`));

  return [...here, ...below].sort();
}

function indexPage(pages: readonly WrittenPage[]): string {
  const rows = pages.map(
    ({ name, title, counts }) => `| [${title}](${name}.md) | ${counts.stated} | ${counts.planned} | ${counts.specs} |`,
  );

  return [
    '# What the tests state',
    '',
    intro(''),
    '',
    'Each page lists, in the words of the test titles, the rules a context holds: a planned rule is an `it.todo` still to write. A rule to change is changed in its spec; the test is the proof, the page its reading.',
    '',
    '| Page | Rules stated | Planned | Specs |',
    '|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

function deleteStalePages(ws: Workspace, kept: ReadonlySet<string>): void {
  for (const file of ws.list(BEHAVIOUR_DIR).filter((name) => name.endsWith('.md') && !kept.has(name))) {
    ws.delete(`${BEHAVIOUR_DIR}/${file}`);
  }
}

function write(ws: Workspace, file: string, content: string): void {
  if (ws.exists(file)) {
    ws.update(file, content);
  } else {
    ws.create(file, content);
  }
}

function capitalised(word: string): string {
  return `${word.charAt(0).toUpperCase()}${word.slice(1).replaceAll('-', ' ')}`;
}

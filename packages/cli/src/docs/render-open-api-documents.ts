import type { OpenApiDocumentConfig } from '../config';

const WIDTH = 120;

const HEADER = `// Generated by \`ddd-ts-kit docs\` from "openapi.documents" of ddd-ts-kit.config.json: never edit it.
import type { OpenApiDocumentSelection } from '@ddd-ts-kit/http/openapi';
`;

/** One document of the config, its contexts read from the sources as the operations they expose. */
export interface ResolvedDocument {
  readonly config: OpenApiDocumentConfig;
  readonly operations: readonly string[];
}

/**
 * The module the contract script and the documentation page read the split of the contract
 * from, laid out as the formatter of the project would: one key per line, a list on one line
 * when it fits. An empty list keeps the contract whole, in one document.
 */
export function renderOpenApiDocuments(documents: readonly ResolvedDocument[]): string {
  const declaration = 'export const OPENAPI_DOCUMENTS: readonly OpenApiDocumentSelection[] = [';

  if (documents.length === 0) {
    return `${HEADER}\n${declaration}];\n`;
  }

  return `${HEADER}\n${declaration}\n${documents.flatMap(documentLines).join('\n')}\n];\n`;
}

function documentLines({ config, operations }: ResolvedDocument): string[] {
  const title: [string, string][] = config.title === undefined ? [] : [['title', config.title]];

  const keys: [string, string | readonly string[]][] = [
    ['name', config.name],
    ...title,
    ['groups', config.groups],
    ['tags', config.tags],
    ['operations', operations],
  ];

  const lines = keys
    .filter(([, value]) => typeof value === 'string' || value.length > 0)
    .flatMap(([key, value]) => (typeof value === 'string' ? [`    ${key}: ${quoted(value)},`] : listLines(key, value)));

  return ['  {', ...lines, '  },'];
}

function listLines(key: string, values: readonly string[]): string[] {
  const inline = `    ${key}: [${values.map(quoted).join(', ')}],`;

  return inline.length <= WIDTH
    ? [inline]
    : [`    ${key}: [`, ...values.map((value) => `      ${quoted(value)},`), '    ],'];
}

/** A string literal as the formatter writes it: single quotes unless the text holds one and no double quote. */
function quoted(text: string): string {
  const escaped = text.replaceAll('\\', '\\\\');

  return text.includes("'") && !text.includes('"') ? `"${escaped}"` : `'${escaped.replaceAll("'", "\\'")}'`;
}

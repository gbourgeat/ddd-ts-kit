import type { NestAnswer } from './nest-answer';
import type { NestControllerEntry, NestRouteMethod } from './nest-controller-entry';

const WIDTH = 120;

/**
 * `<context>.controllers.ts`: the Nest controllers of a context, each with what the signatures of
 * its methods say, for the module to list and the bridge to read: the DTO classes of the parts of
 * the request they take whole, and what they answer. What cannot be read is left out: `@KitRoute`
 * says it, or `nest/controllers-current` reports it.
 */
export function renderControllersFile(
  context: string,
  constant: string,
  entries: readonly NestControllerEntry[],
): string {
  const list =
    entries.length === 0
      ? ' = [];'
      : ` = [\n${entries.map((entry) => `${entryOf(entry.className, entry.methods.flatMap(methodOf))}\n`).join('')}];`;

  return `// Generated by ddd-ts-kit from the Nest controllers of ${context} and the signatures of their methods: never edit it.
${importsOf(entries).join('\n')}

/** The Nest controllers of ${context}, each with what the signatures of its methods say: the module of the context lists them, Nest builds them. */
export const ${constant}: readonly Type<unknown>[]${list}
`;
}

/** The import lines: the bridge and the schema of an identifier when they are used, the controllers, then the DTO classes they name. */
function importsOf(entries: readonly NestControllerEntry[]): string[] {
  const methods = entries.flatMap(({ methods: of }) => of);

  const types = new Map(
    methods
      .flatMap(({ request, answer }) => [...request.map(({ type }) => type), answer])
      .flatMap((type) => (type.kind === 'class' ? [[type.name, type.specifier]] : [])),
  );

  return [
    ...new Set([
      ...(methods.some(({ answer }) => answer.kind === 'accepted')
        ? ["import { acceptedSchema } from '@ddd-ts-kit/http';"]
        : []),
      ...(entries.length === 0 ? [] : ["import { withSignatures } from '@ddd-ts-kit/http/nest';"]),
      "import type { Type } from '@nestjs/common';",
      ...entries.map(({ className, specifier }) => `import { ${className} } from '${specifier}';`),
      ...[...types].map(([name, specifier]) => `import { ${name} } from '${specifier}';`),
    ]),
  ];
}

/** What the signature of a method says, as `withSignatures` takes it; left out when nothing of it was read. */
function methodOf({ name, request, answer }: NestRouteMethod): { name: string; members: string[] }[] {
  const members = [
    ...request.flatMap(({ source, type }) => (type.kind === 'class' ? [`${source}: ${type.name}`] : [])),
    ...answerOf(answer),
  ];

  return members.length === 0 ? [] : [{ name, members }];
}

function answerOf(answer: NestAnswer): string[] {
  if (answer.kind === 'none') {
    return ['answer: null'];
  }

  if (answer.kind === 'accepted') {
    return ['answer: acceptedSchema'];
  }

  return answer.kind === 'class' ? [`answer: ${answer.name}`] : [];
}

/** One entry of the list, each object on one line when the formatter would keep it there. */
function entryOf(className: string, methods: readonly { name: string; members: string[] }[]): string {
  if (methods.length === 0) {
    return `  withSignatures(${className}, {}),`;
  }

  const inline = methods.map(({ name, members }) => `${name}: { ${members.join(', ')} }`);
  const line = `  withSignatures(${className}, { ${inline.join(', ')} }),`;

  if (line.length <= WIDTH) {
    return line;
  }

  const lines = methods.map(({ name, members }, at) => {
    const one = `    ${inline[at] ?? ''},`;

    return one.length <= WIDTH
      ? one
      : `    ${name}: {\n${members.map((member) => `      ${member},\n`).join('')}    },`;
  });

  return `  withSignatures(${className}, {\n${lines.join('\n')}\n  }),`;
}

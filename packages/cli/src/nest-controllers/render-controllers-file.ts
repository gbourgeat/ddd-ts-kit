import type { NestControllerEntry } from './nest-controller-entry';

const WIDTH = 120;

/**
 * `<context>.controllers.ts`: the Nest controllers of a context, each with what its methods answer
 * as their signatures say it, for the module to list and the bridge to read. A method whose answer
 * cannot be read is left out: `@KitRoute` says it, or `nest/controllers-current` reports it.
 */
export function renderControllersFile(
  context: string,
  constant: string,
  entries: readonly NestControllerEntry[],
): string {
  const list =
    entries.length === 0
      ? ' = [];'
      : ` = [\n${entries.map((entry) => `${entryOf(entry.className, answersOf(entry))}\n`).join('')}];`;

  return `// Generated by ddd-ts-kit from the Nest controllers of ${context} and the signatures of their methods: never edit it.
${importsOf(entries).join('\n')}

/** The Nest controllers of ${context}, each with what its methods answer: the module of the context lists them, Nest builds them. */
export const ${constant}: readonly Type<unknown>[]${list}
`;
}

/** The import lines: the bridge and the schema of an identifier when they are used, the controllers, then the DTO classes they answer. */
function importsOf(entries: readonly NestControllerEntry[]): string[] {
  const answers = entries.flatMap(({ methods }) => methods.map(({ answer }) => answer));

  const types = new Map(
    answers.flatMap((answer) => (answer.kind === 'class' ? [[answer.name, answer.specifier]] : [])),
  );

  return [
    ...new Set([
      ...(answers.some(({ kind }) => kind === 'accepted')
        ? ["import { acceptedSchema } from '@ddd-ts-kit/http';"]
        : []),
      ...(entries.length === 0 ? [] : ["import { withAnswers } from '@ddd-ts-kit/http/nest';"]),
      "import type { Type } from '@nestjs/common';",
      ...entries.map(({ className, specifier }) => `import { ${className} } from '${specifier}';`),
      ...[...types].map(([name, specifier]) => `import { ${name} } from '${specifier}';`),
    ]),
  ];
}

/** What each method answers, as `withAnswers` takes it; a method whose answer could not be read is left out. */
function answersOf({ methods }: NestControllerEntry): string[] {
  return methods.flatMap(({ name, answer }) => {
    if (answer.kind === 'none') {
      return [`${name}: null`];
    }

    if (answer.kind === 'accepted') {
      return [`${name}: acceptedSchema`];
    }

    return answer.kind === 'class' ? [`${name}: ${answer.name}`] : [];
  });
}

/** One entry of the list, on one line when the formatter would keep it there. */
function entryOf(className: string, answers: readonly string[]): string {
  if (answers.length === 0) {
    return `  withAnswers(${className}, {}),`;
  }

  const line = `  withAnswers(${className}, { ${answers.join(', ')} }),`;

  return line.length <= WIDTH
    ? line
    : `  withAnswers(${className}, {\n${answers.map((answer) => `    ${answer},\n`).join('')}  }),`;
}

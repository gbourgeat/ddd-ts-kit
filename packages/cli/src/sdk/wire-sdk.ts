import type { Config } from '../config/index.js';
import type { Workspace } from '../workspace/index.js';
import { CLIENTS_DIRECTORY } from './clients-directory.js';
import { editJsonFile } from './edit-json-file.js';
import type { PlannedClient } from './planned-client.js';
import { sdkScripts } from './sdk-scripts.js';
import { withClientPaths } from './with-client-paths.js';
import { withEntry } from './with-entry.js';

const PACKAGES = `${CLIENTS_DIRECTORY}/*`;
const PNPM_WORKSPACE = 'pnpm-workspace.yaml';

/**
 * What the project needs around its clients: each one a workspace package, resolved by its name
 * from the sources (`paths` of tsconfig.json, which the type check, the test runner and knip
 * read), left out of the formatter and of knip, which read generated code as written by hand,
 * and the scripts that generate, compare and build them. Run again, it changes nothing.
 */
export function wireSdk(ws: Workspace, config: Config, clients: readonly PlannedClient[]): void {
  editJsonFile(ws, 'package.json', (manifest) => ({
    ...manifest,
    ...(config.stack.packageManager === 'pnpm' ? {} : { workspaces: withEntry(manifest['workspaces'], PACKAGES) }),
    scripts: sdkScripts(texts(manifest['scripts'])),
  }));

  editJsonFile(ws, 'tsconfig.json', (tsconfig) => withClientPaths(tsconfig, clients));
  editJsonFile(ws, 'biome.json', (biome) => withFormatterExclusion(biome));

  editJsonFile(ws, 'knip.json', (knip) => ({
    ...knip,
    ignoreWorkspaces: withEntry(knip['ignoreWorkspaces'], PACKAGES),
  }));

  if (config.stack.packageManager === 'pnpm') {
    listInPnpmWorkspace(ws);
  }
}

function texts(value: unknown): Record<string, string> {
  const entries = Object.entries(typeof value === 'object' && value !== null ? value : {});

  return Object.fromEntries(entries.filter((entry): entry is [string, string] => typeof entry[1] === 'string'));
}

/** The sources of a client are written by the generator, as Biome would not: they are not formatted. */
function withFormatterExclusion(biome: Record<string, unknown>): Record<string, unknown> {
  const files = biome['files'];

  if (typeof files !== 'object' || files === null || Array.isArray(files)) {
    return biome;
  }

  const includes: unknown = Reflect.get(files, 'includes');

  return { ...biome, files: { ...files, includes: withEntry(includes, `!**/${CLIENTS_DIRECTORY}/*/src`) } };
}

function listInPnpmWorkspace(ws: Workspace): void {
  const text = ws.read(PNPM_WORKSPACE) ?? '';

  if (/^packages:/m.test(text)) {
    if (!text.includes(`'${PACKAGES}'`)) {
      ws.note(
        `${PNPM_WORKSPACE} lists its own packages: add '${PACKAGES}' to them, so that each client is a package of the workspace.`,
      );
    }

    return;
  }

  const content = `${text}${text === '' || text.endsWith('\n') ? '' : '\n'}# The clients of the contract, generated by \`ddd-ts-kit sdk\`.\npackages:\n  - '${PACKAGES}'\n`;

  if (ws.exists(PNPM_WORKSPACE)) {
    ws.update(PNPM_WORKSPACE, content);
  } else {
    ws.create(PNPM_WORKSPACE, content);
  }
}

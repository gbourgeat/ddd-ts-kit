import type { ClientDocument } from './client-document';
import type { ClientOperation } from './client-operation';
import { errorCodes } from './error-codes';
import type { Rpc } from './rpc';
import { isInputOptional } from './is-input-optional';
import { propertyKey } from './property-key';

/** What a README needs besides the document: the package name and where the client sits in its project. */
export interface ReadmePlace {
  readonly packageName: string;
  readonly directory: string;
  /** `orpc` or `trpc` when the API serves its routes as procedures too, which `./orpc` or `./trpc` calls. */
  readonly rpc?: Rpc;
}

/** `README.md` of the package: how to install it, call it, authenticate, handle its refusals; its operations and error codes. */
export function renderReadme(document: ClientDocument, place: ReadmePlace): string {
  return [
    `# ${place.packageName}`,
    `<!-- Generated by \`ddd-ts-kit sdk\` from ${document.source}: never edit it. -->`,
    `The typed client of ${document.title} ${document.version}, generated from its OpenAPI contract. It has no runtime dependency: it calls \`fetch\`, which Node 18 and later, Deno, Bun and every browser provide.`,
    usage(document, place.packageName),
    operationsTable(document.operations),
    codesSection(document),
    ...(place.rpc === 'orpc' ? [procedures(document, place.packageName)] : []),
    ...(place.rpc === 'trpc' ? [trpcProcedures(document, place.packageName)] : []),
    publishing(place),
  ].join('\n\n');
}

function usage(document: ClientDocument, packageName: string): string {
  const first = document.operations[0];

  const call =
    first === undefined
      ? ''
      : `\nconst result = await api.${first.name}(${isInputOptional(first) ? '' : '{ ... }'});\n`;

  const scheme = document.schemes[0]?.[0];
  const credentials = scheme === undefined ? '' : `\n  credentials: { ${scheme}: () => session.token() },`;

  return `## Use

\`\`\`ts
import { createClient, unwrap, isProblem } from '${packageName}';

const api = createClient({ baseUrl: 'https://api.example.com',${credentials} });
${call}\`\`\`

Every method answers the outcome its contract declares, never throws for a declared status: \`result.ok\` and \`result.status\` narrow it to its body (\`result.data\`) or its problem document (\`result.problem\`, whose \`code\` is one of the codes of that status). \`unwrap(api.someOperation(...))\` answers the body of a success and throws a refusal as a \`ProblemError\`, which \`isProblem(error, 'SOME_CODE')\` narrows. A status the contract does not declare throws an \`UnexpectedResponseError\`: a fault of the server (a 500 answered as a problem document, whose \`code\` and \`requestId\`, the reference to quote to the team of the API, it reads), a proxy, or a server and a contract that disagree.

A credential is given per security scheme of the contract, as a value or as a function asked before each request; an operation sends the credentials its security names. A cookie scheme is sent as a \`Cookie\` header, which only a server-side caller can set: in a browser, the browser sends its own cookies (\`fetch\` with \`credentials: 'include'\`). \`headers\` adds headers to every request, \`fetch\` replaces the global one. \`connect(options)\` and the functions of each operation (\`${first?.name ?? 'operation'}(connection, input)\`) are the same calls for a bundle that imports only what it calls.`;
}

function operationsTable(operations: readonly ClientOperation[]): string {
  const rows = operations.map((operation) => {
    const codes = operation.responses.flatMap((response) => response.codes);

    return `| \`${operation.name}\` | \`${operation.method} ${operation.path}\` | ${codes.length === 0 ? '' : codes.join(', ')} |`;
  });

  return ['## Operations', '', '| Method | Request | Error codes |', '| --- | --- | --- |', ...rows].join('\n');
}

function codesSection(document: ClientDocument): string {
  const codes = errorCodes(document);

  return `## Error codes\n\n${codes.length === 0 ? 'The contract declares none.' : codes.map((code) => `- \`${code}\``).join('\n')}\n\n\`ERROR_CODES\` lists them, \`ErrorCode\` is their type.`;
}

function procedures(document: ClientDocument, packageName: string): string {
  const first = document.operations.find((operation) => operation.procedure !== undefined);

  const left = document.operations
    .filter((operation) => operation.procedure === undefined)
    .map(({ name }) => `\`${name}\``);

  const call =
    first === undefined
      ? ''
      : `\nconst [error, data] = await safe(rpc${memberOf(first.procedure ?? first.name)}(${isInputOptional(first) ? '' : '{ ... }'}));\n\nif (isDefinedError(error)) {\n  // error.code is one of the codes of the procedure, error.data its problem document\n}\n`;

  return `## Procedures (oRPC)

The API serves the same operations as oRPC procedures under \`/rpc\`, through the same pipeline: the same credentials, permissions, validation and error codes. \`${packageName}/orpc\` is their client, which needs \`@orpc/client\` and \`@orpc/contract\`; the root entry needs nothing.

\`\`\`ts
import { isDefinedError, safe } from '@orpc/client';
import { createRpcClient } from '${packageName}/orpc';

const rpc = createRpcClient({ url: 'https://api.example.com/rpc', headers: () => ({ authorization: \`Bearer \${session.token()}\` }) });
${call}\`\`\`

A procedure takes the input of its operation (\`path\`, \`query\`, \`header\`, \`body\`) and answers its body. A refusal throws an \`ORPCError\` whose \`code\`, \`status\` and \`data\` are those of the problem document. What only HTTP carries stays with the HTTP client: the headers of an answer (an \`ETag\`, its cache policy), a representation other than JSON, a file or a list streamed as it is read (refused with 406)${left.length === 0 ? '' : `, and the operations no procedure serves, those that receive a file or a raw body: ${left.join(', ')}`}.`;
}

function trpcProcedures(document: ClientDocument, packageName: string): string {
  const first = document.operations.find((operation) => operation.procedure !== undefined);

  const call =
    first === undefined
      ? ''
      : `\ntry {\n  await trpc${memberOf(first.procedure ?? first.name)}.${first.method === 'GET' ? 'query' : 'mutate'}(${isInputOptional(first) ? '' : '{ ... }'});\n} catch (error) {\n  if (isRpcRefusal(error)) {\n    // error.data?.problem?.code is one of the codes of the contract, error.data?.problem its problem document\n  }\n}\n`;

  return `## Procedures (tRPC)

The API serves the same operations as tRPC procedures under \`/trpc\`, through the same pipeline: the same credentials, permissions, validation and error codes. \`${packageName}/trpc\` holds the type of their router, \`AppRouter\`, and a client of it; it needs \`@trpc/client\` and \`@trpc/server\` (for its types); the root entry needs nothing.

\`\`\`ts
import { createRpcClient, isRpcRefusal } from '${packageName}/trpc';

const trpc = createRpcClient({ url: 'https://api.example.com/trpc', headers: () => ({ authorization: \`Bearer \${session.token()}\` }) });
${call}\`\`\`

A procedure is a query for a \`GET\` operation and a mutation for the others; it takes the input of its operation (\`path\`, \`query\`, \`header\`, \`body\`) and answers its body. A refusal throws a \`TRPCClientError\` whose \`data.code\` is the code tRPC has for its status and \`data.problem\` the problem document, with the code of the contract: tRPC types no refusal per procedure. \`AppRouter\` also types a client built by hand, with the links of your choice. What only HTTP carries stays with the HTTP client, as over oRPC, and a binary body too (refused with 406).`;
}

/** How a member is read in TypeScript: \`.name\`, or \`['some-name']\` for a name that is not an identifier. */
function memberOf(name: string): string {
  const key = propertyKey(name);

  return key === name ? `.${name}` : `[${key}]`;
}

function publishing(place: ReadmePlace): string {
  return `## Build and publish

The sources are regenerated by \`ddd-ts-kit sdk\` whenever the contract changes (\`docs:generate\` runs it); \`docs:check\` fails while they differ from the contract. \`npm run sdk:build\` at the root of the project compiles every client to \`dist/\`.

Publishing is a decision of the team, never a step of the pipeline: set \`"sdk.access"\` in ddd-ts-kit.config.json (\`restricted\` for a private scope or registry, \`public\`), regenerate, then \`npm publish --workspace ${place.directory}\` with the version of \`package.json\` raised. A registry other than npm is named in an \`.npmrc\` next to this file.
`;
}

import type { ClientDocument } from './client-document.js';
import type { ClientOperation } from './client-operation.js';
import { errorCodes } from './error-codes.js';
import { isInputOptional } from './is-input-optional.js';

/** What a README needs besides the document: the package name and where the client sits in its project. */
export interface ReadmePlace {
  readonly packageName: string;
  readonly directory: string;
}

/** `README.md` of the package: how to install it, call it, authenticate, handle its refusals; its operations and error codes. */
export function renderReadme(document: ClientDocument, place: ReadmePlace): string {
  return [
    `# ${place.packageName}`,
    `<!-- Generated by \`ddd-ts-kit sdk\` from ${document.source}: never edit it. -->`,
    `The typed client of ${document.title} ${document.version}, generated from its OpenAPI contract. It has no runtime dependency: it calls \`fetch\`, which Node 18 and later, Deno, Bun and every browser provide.`,
    usage(document, place.packageName),
    operationsTable(document.operations),
    codesSection(document),
    publishing(place),
  ].join('\n\n');
}

function usage(document: ClientDocument, packageName: string): string {
  const first = document.operations[0];

  const call =
    first === undefined
      ? ''
      : `\nconst result = await api.${first.name}(${isInputOptional(first) ? '' : '{ ... }'});\n`;

  const scheme = document.schemes[0]?.[0];
  const credentials = scheme === undefined ? '' : `\n  credentials: { ${scheme}: () => session.token() },`;

  return `## Use

\`\`\`ts
import { createClient, unwrap, isProblem } from '${packageName}';

const api = createClient({ baseUrl: 'https://api.example.com',${credentials} });
${call}\`\`\`

Every method answers the outcome its contract declares, never throws for a declared status: \`result.ok\` and \`result.status\` narrow it to its body (\`result.data\`) or its problem document (\`result.problem\`, whose \`code\` is one of the codes of that status). \`unwrap(api.someOperation(...))\` answers the body of a success and throws a refusal as a \`ProblemError\`, which \`isProblem(error, 'SOME_CODE')\` narrows. A status the contract does not declare throws an \`UnexpectedResponseError\`.

A credential is given per security scheme of the contract, as a value or as a function asked before each request; an operation sends the credentials its security names. \`headers\` adds headers to every request, \`fetch\` replaces the global one. \`connect(options)\` and the functions of each operation (\`${first?.name ?? 'operation'}(connection, input)\`) are the same calls for a bundle that imports only what it calls.`;
}

function operationsTable(operations: readonly ClientOperation[]): string {
  const rows = operations.map((operation) => {
    const codes = operation.responses.flatMap((response) => response.codes);

    return `| \`${operation.name}\` | \`${operation.method} ${operation.path}\` | ${codes.length === 0 ? '' : codes.join(', ')} |`;
  });

  return ['## Operations', '', '| Method | Request | Error codes |', '| --- | --- | --- |', ...rows].join('\n');
}

function codesSection(document: ClientDocument): string {
  const codes = errorCodes(document);

  return `## Error codes\n\n${codes.length === 0 ? 'The contract declares none.' : codes.map((code) => `- \`${code}\``).join('\n')}\n\n\`ERROR_CODES\` lists them, \`ErrorCode\` is their type.`;
}

function publishing(place: ReadmePlace): string {
  return `## Build and publish

The sources are regenerated by \`ddd-ts-kit sdk\` whenever the contract changes (\`docs:generate\` runs it); \`docs:check\` fails while they differ from the contract. \`npm run sdk:build\` at the root of the project compiles every client to \`dist/\`.

Publishing is a decision of the team, never a step of the pipeline: set \`"sdk.access"\` in ddd-ts-kit.config.json (\`restricted\` for a private scope or registry, \`public\`), regenerate, then \`npm publish --workspace ${place.directory}\` with the version of \`package.json\` raised. A registry other than npm is named in an \`.npmrc\` next to this file.
`;
}

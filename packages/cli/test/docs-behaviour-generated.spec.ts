import { describe, expect, it } from 'vitest';
import { behaviourPages, behaviourProject, specOf } from './support/behaviour-project';

const UNIT = 'src/contexts/billing/test/unit';

describe('The page of a context, the titles the kit generated listed apart', () => {
  const root = behaviourProject({
    [`${UNIT}/cancel-invoice.handler.spec.ts`]: specOf('Cancel invoice', [
      'applies the business decision to the invoice (planned)',
      'saves the invoice and answers its identifier',
      'refuses to cancel an invoice twice (planned)',
      'is refused to an actor who does not hold the permission invoice.cancel',
      'refuses an invoice already paid',
    ]),
    [`${UNIT}/invoice.aggregate.spec.ts`]: specOf('Invoice', [
      'is born with its identity',
      'saves the invoice and answers its identifier',
    ]),
    [`${UNIT}/invoice-already-paid.error.spec.ts`]: specOf('Refusal: invoice already paid', [
      'refuses already paid with the code INVOICE_ALREADY_PAID',
      'refuses an invoice that was paid before it was issued with the code INVOICE_ALREADY_PAID',
    ]),
  });

  const page = behaviourPages(root);

  it('lists the rules written for the project first, those still to write after them, then the titles of the templates apart', () => {
    expect(page('billing')).toContain(
      [
        '- **Cancel invoice**',
        '  - refuses an invoice already paid',
        '  - refuses to cancel an invoice twice (planned)',
        '- *Generated by the kit*',
        '  - saves the invoice and answers its identifier',
        '  - is refused to an actor who does not hold the permission invoice.cancel',
        '  - applies the business decision to the invoice (planned)',
        '',
      ].join('\n'),
    );
  });

  it('reads a title as generated only in a spec of the role its template writes, a name where the template has one, and counts the generated titles on the page and in the index', () => {
    expect(page('billing')).toContain(
      [
        '- **Invoice**',
        '  - saves the invoice and answers its identifier',
        '- *Generated by the kit*',
        '  - is born with its identity',
      ].join('\n'),
    );

    expect(page('billing')).toContain(
      [
        '- **Refusal: invoice already paid**',
        '  - refuses an invoice that was paid before it was issued with the code INVOICE_ALREADY_PAID',
        '- *Generated by the kit*',
        '  - refuses already paid with the code INVOICE_ALREADY_PAID',
      ].join('\n'),
    );

    expect(page('billing')).toContain(
      '7 rules stated, 2 planned, in 3 specs. Of the 9 titles, 5 are as the kit generated them, listed apart under each heading.',
    );

    expect(page('README')).toContain('| [billing](billing.md) | 7 | 2 | 5 of 9 | 3 |');
  });
});

describe('The page of a context, each template read for the specs of its role', () => {
  const root = behaviourProject({
    'src/contexts/billing/test/integration/simulated-exchange-rates.adapter.spec.ts': specOf(
      'Simulated exchange rates',
      ['is built with nothing from the environment: it reaches nothing outside the process'],
    ),
    [`${UNIT}/billing.routes.spec.ts`]: specOf('The routes of billing', [
      'answer each method and path once, each under an operation of its own',
    ]),
    [`${UNIT}/cancel-invoice.handler.spec.ts`]: specOf('Cancel invoice', [
      'answer each method and path once, each under an operation of its own',
    ]),
  });

  const page = behaviourPages(root);

  it('reads the titles of the template of a simulated adapter in the spec of an adapter', () => {
    expect(page('billing')).toContain(
      [
        '### simulated-exchange-rates (adapter), in integration',
        '',
        '`integration/simulated-exchange-rates.adapter.spec.ts`',
        '',
        '- *Generated by the kit*',
        '  - is built with nothing from the environment: it reaches nothing outside the process',
      ].join('\n'),
    );
  });

  it('reads the titles of the template of the routes of a context in that spec alone, never in a spec of another role', () => {
    expect(page('billing')).toContain(
      '### billing (routes), in unit\n\n`unit/billing.routes.spec.ts`\n\n- *Generated by the kit*\n',
    );

    expect(page('billing')).toContain(
      '- **Cancel invoice**\n  - answer each method and path once, each under an operation of its own\n',
    );
  });
});

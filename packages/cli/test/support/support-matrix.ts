import type { StackOptions } from '../../src/init/stack/stack-options';

/**
 * Why a combination is refused: `decided`, the kit does not support it by design; `not yet`, a
 * package of the kit can do it and the generator does not write it yet, a gap that stays visible
 * here until it is filled.
 */
export type RefusalKind = 'decided' | 'not yet';

export interface DeclaredRefusal {
  /** The message of the refusal, its values listed: a new value refused the same way is a new decision. */
  readonly refusal: RegExp;
  /** A combination refused so, which proves that the line still holds. */
  readonly example: Partial<StackOptions>;
  readonly kind: RefusalKind;
  readonly why: string;
}


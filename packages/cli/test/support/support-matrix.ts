/** A platform todo or a package of the kit that some members of a family of flags get and others not, and why. */
export interface DeclaredDifference {
  readonly family: string;
  /** The todo (`TODO(platform): ...`) or the package (`package @ddd-ts-kit/...`), the member named `<member>`. */
  readonly trait: RegExp;
  readonly kind: RefusalKind;
  /** The members without it, each with its reason. */
  readonly without: Readonly<Record<string, string>>;
}


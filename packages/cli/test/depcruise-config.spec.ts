import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { parseConfig } from '../src/config';
import { cruiseConfiguration } from '../src/depcruise/cruise-configuration';
import { cli, read, REPO_ROOT, scaffoldEverything, tempDir, write } from './helpers';
import { jsonAt } from './support/json-at';
import { readJson } from './support/read-json';
import { stringsAt } from './support/strings-at';

const FILE = '.dependency-cruiser.cjs';

describe('depcruise-config', () => {
  let root: string;

  beforeAll(() => {
    root = tempDir('depcruise');
    scaffoldEverything(root);
  });

  it('is generated by init and kept current by generate', () => {
    const file = read(root, FILE);

    expect(cli(root, 'depcruise-config', '--check').stdout).toBe(`${FILE} is up to date.`);
    expect(file.startsWith('// Generated by `ddd-ts-kit depcruise-config`')).toBe(true);
    expect(file).toContain('"shipping\\" imports the published language of a context that is not one of its upstreams');
    expect(file).toContain('^src/contexts/(shipping|billing)/');
  });

  it('prints the configuration, reports a stale file and writes it again', () => {
    const config = readJson(root, 'ddd-ts-kit.config.json');
    const upstreams = jsonAt(config, 'contexts', 'order-fulfilment', 'upstreams');

    if (Array.isArray(upstreams)) {
      upstreams.push({ context: 'billing', relationship: 'conformist' });
    }

    write(root, 'ddd-ts-kit.config.json', JSON.stringify(config, null, 2));

    const stale = cli(root, 'depcruise-config', '--check');

    expect(stale.code).toBe(1);
    expect(stale.stdout).toContain(`stale  ${FILE}`);
    expect(cli(root, 'depcruise-config', '--check', '--json').json()).toEqual({ ok: false, file: FILE });
    expect(cli(root, 'depcruise-config').stdout).toContain('^src/contexts/(order-fulfilment|billing)/');
    expect(cli(root, 'depcruise-config', '--write').stdout).toBe(`written  ${FILE}`);
    expect(cli(root, 'depcruise-config', '--check').code).toBe(0);
    expect(`${cli(root, 'depcruise-config').stdout}\n`).toBe(read(root, FILE));
  });

  it('speaks of ports, and leaves the files discovery loads out of the orphans, jobs and publishers included', () => {
    const discovered = tempDir('depcruise');

    cli(discovered, 'init', '--assembly', 'discovery', '--broker', 'nats');

    expect(read(root, FILE)).toContain(
      'declare the need as a port, an abstract class in domain/repositories or application/ports.',
    );

    expect(read(root, FILE)).not.toContain('integration-handler|event-handler|publisher|policy|job');
    expect(read(root, FILE)).not.toContain('.dependencies');

    expect(read(discovered, FILE)).toContain(
      '(command|query|handler|integration-handler|event-handler|publisher|policy|job|background-job|projection|repository|gateway|adapter)',
    );

    expect(read(discovered, FILE)).toContain('/[^/]+/[^/]+\\\\.dependencies\\\\.ts$');
  });
});

describe('depcruise-config against the script of the pipeline', () => {
  // Next to the tests so that the script resolves `typescript` like a project would.
  const sandbox = path.join(REPO_ROOT, 'packages/cli/test', `.depcruise-${process.pid}`);

  const projectConfig = {
    sourceRoot: 'app',
    contextsDir: 'app/contexts',
    stack: { validation: 'class-validator' },
    contexts: {
      billing: { classification: 'core', upstreams: [] },
      'order-fulfilment': { classification: 'generic', upstreams: [{ context: 'billing' }, 'catalog'] },
      catalog: { classification: 'generic' },
    },
    domainAllowedPackages: ['@ddd-ts-kit/kernel', 'decimal.js'],
    // Written out, as `init` does: the shipped script does not know that the application layer may import the auth package by default.
    applicationAllowedPackages: ['@ddd-ts-kit/kernel', '@ddd-ts-kit/auth'],
  };

  beforeAll(() => {
    fs.mkdirSync(sandbox, { recursive: true });
    fs.copyFileSync(path.join(REPO_ROOT, 'pipeline/depcruise-config.mjs'), path.join(sandbox, 'depcruise-config.mjs'));
    fs.writeFileSync(path.join(sandbox, 'ddd-ts-kit.config.json'), JSON.stringify(projectConfig));
  });

  it.each(['zod', 'class-validator', 'typebox', 'standard-schema', 'none'])(
    'lets a background job import the same schema packages under %s, and writes the same layer rules',
    async (validation) => {
      const config = { ...projectConfig, stack: { validation } };

      fs.writeFileSync(path.join(sandbox, 'ddd-ts-kit.config.json'), JSON.stringify(config));

      // a query of its own: the module is read again for the config written above
      const loaded: unknown = await import(
        `${pathToFileURL(path.join(sandbox, 'depcruise-config.mjs')).href}?${validation}`
      );

      const shipped = rulesOf(jsonAt(loaded, 'default')).filter(isLayerRule);
      const ported = rulesOf(JSON.parse(JSON.stringify(cruiseConfiguration(parseConfig(config))))).filter(isLayerRule);

      fs.writeFileSync(path.join(sandbox, 'ddd-ts-kit.config.json'), JSON.stringify(projectConfig));

      expect(shipped).toEqual(ported);
    },
  );

  afterAll(() => {
    fs.rmSync(sandbox, { recursive: true, force: true });
  });

  it('builds the same rules and options, plus the fakes, the worlds and the entry points of single contexts among the files that may have no importer', async () => {
    const shipped: unknown = jsonAt(
      await import(pathToFileURL(path.join(sandbox, 'depcruise-config.mjs')).href),
      'default',
    );

    const ported: unknown = JSON.parse(JSON.stringify(cruiseConfiguration(parseConfig(projectConfig))));
    const orphansOf = (configuration: unknown): string[] => stringsAt(orphanRule(configuration), 'from', 'pathNot');
    // An entry point of a context run alone has no importer either; the port follows `platformDir` for tracing.ts, the same place by default.
    const added = orphansOf(ported).filter((pattern) => !orphansOf(shipped).includes(pattern));

    expect(added).toEqual([
      '^app/apps/[^/]+/main\\.ts$',
      '^app/contexts/[^/]+/test/fakes/',
      '^app/contexts/[^/]+/test/worlds/',
    ]);

    expect(orphansOf(ported).filter((pattern) => !added.includes(pattern))).toEqual(orphansOf(shipped));
    expect(withoutOrphans(ported)).toEqual(withoutOrphans(JSON.parse(JSON.stringify(shipped))));
  });
});

function orphanRule(configuration: unknown): unknown {
  return rulesOf(configuration).find((rule) => jsonAt(rule, 'name') === 'no-orphans');
}

function withoutOrphans(configuration: unknown): unknown {
  return {
    rules: rulesOf(configuration).filter((rule) => jsonAt(rule, 'name') !== 'no-orphans'),
    options: jsonAt(configuration, 'options'),
  };
}

function rulesOf(configuration: unknown): unknown[] {
  const forbidden = jsonAt(configuration, 'forbidden');

  return Array.isArray(forbidden) ? forbidden : [];
}

function isLayerRule(rule: unknown): boolean {
  return String(jsonAt(rule, 'name')).startsWith('layer-');
}

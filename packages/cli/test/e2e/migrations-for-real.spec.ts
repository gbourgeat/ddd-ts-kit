import pg from 'pg';
import { describe, expect, it } from 'vitest';
import { cli, tempDir } from '../helpers';
import { installForReal } from './install-for-real';
import { runIn } from './run-in';
import { SLOW } from './stacks';

/** A PostgreSQL server whose user may create databases, `postgres://app:app@localhost:5432`: the pipeline starts one. */
const SERVER = process.env['DDD_TS_KIT_MIGRATIONS_SERVER'];

/** The triggers that keep the audit trail append-only, as `@ddd-ts-kit/audit` names them. */
const GUARD = [
  'audit_archives_no_rewrite',
  'audit_archives_no_truncate',
  'audit_entries_no_rewrite',
  'audit_entries_no_truncate',
];

/** The tools that generate migrations from a schema, and the name `db:generate` takes on each. */
const TOOLS = [
  ['drizzle', 'init'],
  ['prisma', 'init'],
  ['typeorm', 'migrations/init'],
] as const;

/**
 * Slow, opt-in (DDD_TS_KIT_E2E=1 and DDD_TS_KIT_MIGRATIONS_SERVER): a project with an audit trail,
 * installed for real, generates its first migration with the tool of its ORM, applies it to a
 * real PostgreSQL and stays green, the audit trail append-only from that first migration.
 */
describe.runIf(SLOW && SERVER !== undefined)('the first migration of a generated project, on a real PostgreSQL', () => {
  it.each(TOOLS)(
    'is generated by the tool of %s, guarded, applied, and leaves every gate green',
    async (orm, name) => {
      const database = `migrations_${orm}`;
      const url = `${SERVER ?? ''}/${database}`;
      const root = tempDir(`migrations-${orm}`);

      const sh = (command: string): string =>
        runIn(root, { command: 'sh', args: ['-c', `${command} 2>&1`], env: { DATABASE_URL: url } });

      await renewed(database);
      expect(cli(root, 'init', '--orm', orm, '--audit', 'on', '--package-manager', 'npm').code).toBe(0);
      installForReal(root, 'npm');
      sh(orm === 'typeorm' ? 'npm run build && npm run db:generate ' + name : `npm run db:generate ${name}`);
      sh(orm === 'typeorm' ? 'npm run build && npm run db:migrate' : 'npm run db:migrate');

      expect(await triggersOf(url)).toEqual(GUARD);
      // Each gate fails the shell, and so the spec, on a finding.
      sh('npm run typecheck && npm run lint && npm run format:check && npm run check:arch && npm run deadcode');
    },
    1_200_000,
  );
});

async function renewed(database: string): Promise<void> {
  const client = new pg.Client({ connectionString: `${SERVER ?? ''}/postgres` });

  await client.connect();
  await client.query(`drop database if exists ${database} with (force)`);
  await client.query(`create database ${database}`);
  await client.end();
}

async function triggersOf(url: string): Promise<string[]> {
  const client = new pg.Client({ connectionString: url });

  await client.connect();

  const { rows } = await client.query<{ tgname: string }>(
    "select tgname from pg_trigger where tgname like 'audit_%' order by tgname",
  );

  await client.end();

  return rows.map((row) => row.tgname);
}
